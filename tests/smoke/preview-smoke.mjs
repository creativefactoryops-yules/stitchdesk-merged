// Smoke test of the single-file phone preview, opened straight from disk (file://, no server).
import { chromium } from 'playwright';
const FILE = process.env.PREVIEW ?? new URL('../../../preview/index.html', import.meta.url).href;
let fails = 0;
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
page.on('pageerror', (e) => { console.log('PAGE ERROR', e.message); fails++; });
await page.goto(FILE + '#/s/maple-demo');
await page.getByRole('heading', { level: 1, name: 'Chat with Stitch' }).waitFor();
ok(true, 'preview opens from file:// with hash routing');
await page.getByLabel('Your message').fill('width is 80 and depth is 36 inches, it is a sofa');
await page.getByRole('button', { name: 'Send', exact: true }).click();
await page.locator('.msg.offline').waitFor();
ok((await page.locator('.msg.offline').innerText()).includes('Stitch is offline'), 'no server: honest offline notice, no fake answer');
ok(/Width\s*80 in/.test(await page.locator('.sheet').innerText()), 'job sheet still fills offline');
await page.getByLabel('Shop sections').getByRole('link', { name: 'Book this' }).click();
await page.getByLabel('Your name').fill('Phone Tester');
await page.getByRole('textbox', { name: 'Phone' }).fill('416-555-0100');
const d = new Date(); d.setDate(d.getDate() + 2);
await page.getByLabel('First choice').fill(d.toLocaleDateString('en-CA'));
await page.getByRole('button', { name: 'Send booking request' }).click();
await page.getByRole('heading', { level: 1, name: 'Request sent' }).waitFor();
await page.goto(FILE + '#/shop/jobs');
await page.getByRole('heading', { level: 1, name: 'Jobs board' }).waitFor();
ok((await page.locator('section[aria-labelledby="col-lead"]').innerText()).includes('Sofa for Phone Tester'), 'booking appears on the shop board');
await page.screenshot({ path: '/tmp/stitch-shots/08-preview-board.png' });
await b.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
